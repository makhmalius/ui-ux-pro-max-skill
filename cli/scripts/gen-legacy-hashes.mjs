#!/usr/bin/env node
// Regenerates src/utils/legacy-skill-hashes.ts: sha256 (CRLF normalised to LF)
// of every historical SKILL.md of each bundled sub-skill, from git history of
// cli/assets/skills/<name> and .claude/skills/<name>, plus the current bundle.
// Usage: node cli/scripts/gen-legacy-hashes.mjs   (needs full git history)
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { assertFullHistory } from './git-history.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'buffer', maxBuffer: 1 << 28 });
assertFullHistory(git('rev-parse', '--is-shallow-repository').toString());
const sha = buf => createHash('sha256').update(buf.toString('utf-8').replace(/\r\n/g, '\n')).digest('hex');

const names = readdirSync(join(root, 'cli', 'assets', 'skills'), { withFileTypes: true })
  .filter(e => e.isDirectory()).map(e => e.name).sort();

const out = {};
for (const name of names) {
  const hashes = new Set();
  hashes.add(sha(readFileSync(join(root, 'cli', 'assets', 'skills', name, 'SKILL.md'))));
  for (const path of [`cli/assets/skills/${name}/SKILL.md`, `.claude/skills/${name}/SKILL.md`]) {
    const shas = git('log', '--all', '--format=%H', '--', path).toString().split('\n').filter(Boolean);
    for (const c of shas) {
      try {
        const entry = git('ls-tree', c, '--', path).toString();
        if (!entry || entry.startsWith('120000')) continue; // deleted or symlink pointer
        hashes.add(sha(git('show', `${c}:${path}`)));
      } catch { /* file absent in that commit */ }
    }
  }
  out[name] = [...hashes].sort();
}

const body = Object.entries(out)
  .map(([n, h]) => `  '${n}': [\n${h.map(x => `    '${x}',`).join('\n')}\n  ],`).join('\n');
writeFileSync(join(root, 'cli', 'src', 'utils', 'legacy-skill-hashes.ts'),
`// GENERATED by: node cli/scripts/gen-legacy-hashes.mjs  (do not edit by hand)
// sha256 of every SKILL.md (CRLF->LF) ever shipped for each bundled sub-skill,
// taken from \`git log --all -- cli/assets/skills/<name>/SKILL.md\` and
// \`.claude/skills/<name>/SKILL.md\`, plus the current bundle. Closed set: every
// install made after the ownership marker was introduced carries the marker.
export const LEGACY_SKILL_HASHES: Record<string, string[]> = {
${body}
};
`);
console.log('wrote legacy-skill-hashes.ts', Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.length])));
